#!/usr/bin/env node
/**
 * Grokの縮小案を完全却下した上で、gemini-3-pro-preview にレビュー依頼
 * 深層心理・CVR/LTV・変換率の観点から参考になる示唆を得る
 *
 * 実行: node scripts/ask-gemini-review-grok-proposal.js
 */

require("dotenv").config();
const fs = require("fs");
const path = require("path");
const { GoogleGenerativeAI } = require("@google/generative-ai");

const GEMINI_API_KEY = process.env.GEMINI_API_KEY;
const GEMINI_MODEL = "gemini-3-pro-preview";

if (!GEMINI_API_KEY) {
  console.error("❌ GEMINI_API_KEY is not set");
  process.exit(1);
}

const grokReviewPath = path.join(
  __dirname,
  "../docs/ai-analysis-results/GROK_SALES_LETTER_X_ALGORITHM_REVIEW_20260204T035740.md"
);

function loadGrokProposal() {
  if (fs.existsSync(grokReviewPath)) {
    return fs.readFileSync(grokReviewPath, "utf-8");
  }
  return "(Grok提案ファイルが見つかりません)";
}

async function main() {
  const grokProposal = loadGrokProposal();

  const prompt = `あなたは深層心理学とマーケティング・コンバージョン最適化の専門家です。

## 背景

Grok（grok-4-1-fast-reasoning）が、Grokセールスレター（引用リポスト用の5パート構造）のXアルゴリズム改善案を出しました。
その内容は「投稿頻度削減（300→50-100/言語）」「構造短縮（150-200文字）」「リンク4本→2本」「インフルエンサー300→100人」など、縮小・制限を主軸とした提案でした。

**その縮小案は完全に不採用・却下します。** スケール戦略（1日300+投稿・6言語・300人ローテーション）は維持します。

## 依頼

縮小案そのものは却下済みですが、Grokの提案文を読んだ上で、**深層心理・CVR/LTV・変換率**の観点から、あなたの専門性で参考になる示唆を出してください。

- Grok案のうち「捨てずに考えておく価値がある」要素はあるか（あれば理由と適用の仕方）
- 縮小しない前提で、心理・コンバージョン面で強化できる点
- 5パート構造（HEADLINE→PERSONA HOOK→PRODUCT INTRO→OBJECTION→HASHTAGS）やリンクブロックについて、心理的に刺さる工夫

日本語で回答。実装即効レベルの具体性を。`;

  const fullPrompt = `${prompt}

---

## Grokの提案（参考・縮小案は却下済み）

${grokProposal}
`;

  try {
    console.log(`🔄 Gemini (${GEMINI_MODEL}) に Grok提案のレビューを依頼中...\n`);

    const genAI = new GoogleGenerativeAI(GEMINI_API_KEY);
    const model = genAI.getGenerativeModel({
      model: GEMINI_MODEL,
      generationConfig: {
        temperature: 0.6,
        maxOutputTokens: 4000
      }
    });

    const result = await model.generateContent(fullPrompt);
    const response = result.response;
    const text = response.text();

    console.log("=".repeat(80));
    console.log("📊 Gemini レビュー（Grok縮小案を却下した上での示唆）");
    console.log("=".repeat(80));
    console.log(text);
    console.log("\n" + "=".repeat(80));

    const usage = response.usageMetadata || {};
    console.log("📈 API使用量:", usage.totalTokenCount || "N/A");
    console.log("=".repeat(80));

    const outDir = path.join(__dirname, "../docs/ai-analysis-results");
    if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
    const outPath = path.join(
      outDir,
      `GEMINI_REVIEW_GROK_PROPOSAL_REJECTED_${new Date().toISOString().slice(0, 19).replace(/[:-]/g, "")}.md`
    );
    const md = `# Gemini レビュー: Grok縮小案を却下した上での示唆

**生成日時**: ${new Date().toISOString()}
**モデル**: ${GEMINI_MODEL}

## 前提
- Grokの縮小案（頻度削減・文字数短縮・リンク削減・インフル減）は完全不採用・却下
- スケール戦略（300+投稿/日・6言語・300人ローテーション）は維持

## Gemini レビュー

${text}

---
*Generated by scripts/ask-gemini-review-grok-proposal.js*
`;
    fs.writeFileSync(outPath, md, "utf-8");
    console.log(`\n✅ 保存: ${outPath}`);

    return { success: true, text };
  } catch (error) {
    console.error("❌ Gemini API エラー:", error.message);
    process.exit(1);
  }
}

main();

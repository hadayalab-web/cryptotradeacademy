#!/usr/bin/env node
/**
 * GrokセールスレターのXアルゴリズム適合性を grok-4-1-fast-reasoning に再評価依頼
 * 「今の実装以上に改善するべきところはない」と以前Grokが言っていたが本当か確認
 */

require("dotenv").config();
const fs = require("fs");
const path = require("path");
const OpenAI = require("openai");

const XAI_API_KEY = process.env.XAI_API_KEY;
const XAI_BASE_URL = process.env.XAI_BASE_URL || "https://api.x.ai/v1";

if (!XAI_API_KEY) {
  console.error("❌ XAI_API_KEY is not set");
  process.exit(1);
}

const grokClient = new OpenAI({
  apiKey: XAI_API_KEY,
  baseURL: XAI_BASE_URL
});

// 現在のGrokセールスレター実装の概要（services/salesLetterContest.js より）
const IMPLEMENTATION_SUMMARY = `
## 現在のGrokセールスレター実装（引用リポスト用）

### 5パート構造（buildGrokOnlyPrompt で生成）
1. **HEADLINE**: 1行。問い・痛み・好奇心。Trap Score や市場を参照。絵文字1つ（例: 🔴）。
2. **PERSONA HOOK（思考停止・鷲掴み）**: 1段落。「ただ見てるだけ」ループ、未実現損、引き金を引けない人向け。共感、非難なし。
3. **PRODUCT INTRO**: Minimal Version（無料）と Regular Briefing（有料）の紹介。各1段落。
4. **OBJECTION HANDLING（反論処理）**: 2文のみ。躊躇への共感→リフレーム。
5. **HASHTAGS**: 3つ厳選（#BTC #TrapDefence +1言語別）。

### リンクブロック（本文直下に定型で付与）
- ▼ 無料ビデオ → VSL_MINIMAL
- 👇 無料登録（カード不要）→ Whop Minimal checkout
- ▼ 有料版ビデオ → VSL_REGULAR
- ▼ Regular Briefing（コード DEFEND50）→ Whop Regular

### 運用
- 6言語（en, ja, es, pt-br, ar, ko）で事前キャッシュ生成
- 引用リポスト形式: 300人インフルエンサーのtweetを引用して、上記セールスレター+リンクブロックをコメントとして投稿
- 1日300+投稿を6言語でローテーション
`;

async function main() {
  const prompt = `あなたはX（Twitter）アルゴリズムと引用リポスト戦略の専門家です。

以前、ある開発者に対して「Grokセールスレターの実装はXアルゴリズム的には今の実装以上に改善するべきところはない」とアドバイスしたと伝えられています。

以下が現在の実装の詳細です。この実装をXアルゴリズム最適化の観点から**厳密に再評価**してください。

${IMPLEMENTATION_SUMMARY}

## 依頼事項

1. **「改善の余地なし」の妥当性**: 本当にこの実装以上にXアルゴリズム適合性を高める具体的な改善点はないでしょうか？
2. **あれば具体的な改善案**: もし改善すべき点がある場合、実装即適用レベルで具体的に挙げてください（プロンプト変更、フォーマット変更、リンク順序、ハッシュタグ、文字数など）。
3. **変えない方がよい点**: 現状維持が正しいと判断する要素があれば理由とともに記載してください。

日本語で回答してください。客観的かつデータ・根拠を踏まえた分析を期待しています。`;

  try {
    console.log("🔄 grok-4-1-fast-reasoning に GrokセールスレターのXアルゴリズム再評価を依頼中...\n");

    const response = await grokClient.chat.completions.create({
      model: "grok-4-1-fast-reasoning",
      messages: [
        {
          role: "system",
          content:
            "あなたはX（Twitter）アルゴリズムとコンテンツ最適化の専門家です。引用リポスト・インプレッション・エンゲージメント最大化についてデータドリブンな分析を行います。過去の自分の発言についても客観的に再評価し、改善点があれば正直に指摘します。"
        },
        {
          role: "user",
          content: prompt
        }
      ],
      temperature: 0.6,
      max_tokens: 4000
    });

    const analysis = response.choices[0]?.message?.content || "";
    const usage = response.usage || {};

    console.log("=".repeat(80));
    console.log("📊 Grokセールスレター Xアルゴリズム再評価");
    console.log("=".repeat(80));
    console.log(analysis);
    console.log("\n" + "=".repeat(80));
    console.log("📈 API使用量:");
    console.log(`  入力: ${usage.prompt_tokens || 0} / 出力: ${usage.completion_tokens || 0} / 合計: ${usage.total_tokens || 0}`);
    console.log("=".repeat(80));

    // docs に保存
    const outDir = path.join(__dirname, "../docs/ai-analysis-results");
    if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });
    const outPath = path.join(
      outDir,
      `GROK_SALES_LETTER_X_ALGORITHM_REVIEW_${new Date().toISOString().slice(0, 19).replace(/[:-]/g, "")}.md`
    );
    const md = `# Grokセールスレター Xアルゴリズム再評価

**生成日時**: ${new Date().toISOString()}
**モデル**: grok-4-1-fast-reasoning

## 依頼文
「今の実装以上に改善するべきところはない」と以前Grokが言っていたが本当か、再評価依頼。

## 分析結果

${analysis}

---
*Generated by scripts/ask-grok-sales-letter-x-algorithm-review.js*
`;
    fs.writeFileSync(outPath, md, "utf-8");
    console.log(`\n✅ 保存: ${outPath}`);

    return { success: true, analysis };
  } catch (error) {
    console.error("❌ Grok API エラー:", error.message);
    process.exit(1);
  }
}

main();
